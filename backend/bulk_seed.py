async def bulk_seed():
    async with AsyncSessionLocal() as db:
        for num, nome, end, cnpj, sind, cpf in CONDO_DATA:
            # Check if exists
            res = await db.execute(select(Condominio).where(Condominio.numero == num))
            if res.scalar_one_or_none():
                print(f"Skipping {num} - already exists")
                continue
            
            condo = Condominio(
                numero=num,
                nome=nome,
                endereco=end,
                cnpj=cnpj,
                sindico=sind,
                cpf_sindico=cpf,
                ativo=True
            )
            db.add(condo)
            print(f"Adding {num} - {nome}")
        
        await db.commit()
        print("Bulk seed completed.")

if __name__ == "__main__":
    asyncio.run(bulk_seed())
